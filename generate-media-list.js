const fs = require('fs');
const path = require('path');

const PUBLIC_DIR = path.join(__dirname, 'public');
const BASE_PATH = '';
const IMAGES_DIR = path.join(PUBLIC_DIR, 'images');
const OUTPUT_FILE = path.join(__dirname, 'data', 'media-list.ts');

const EXT_IMAGES = ['.jpg', '.jpeg', '.png', '.webp', '.gif', '.svg'];
const EXT_VIDEOS = ['.mp4', '.webm', '.ogg', '.mov'];

// Sync captions from data/site.ts galleryCaptions
let KNOWN_DESCRIPTIONS = {};
try {
  const sitePath = path.join(__dirname, 'data', 'site.ts');
  const siteSource = fs.readFileSync(sitePath, 'utf8');
  const block = siteSource.match(/export const galleryCaptions[^=]*=\s*(\{[\s\S]*?\});/);
  if (block) {
    KNOWN_DESCRIPTIONS = Function(`"use strict"; return (${block[1]});`)();
  }
} catch (_) {
  KNOWN_DESCRIPTIONS = {};
}

function cleanName(filename, category) {
  const ext = path.extname(filename);
  let nameWithoutExt = path.basename(filename, ext);

  // If there's a copy suffix like (1), clean it
  nameWithoutExt = nameWithoutExt.replace(/\s*\(\d+\)\s*/g, '');

  if (nameWithoutExt.startsWith('PinLoad_')) {
    // Extract readable name from PinLoad files
    let parts = nameWithoutExt.replace('PinLoad_', '').split('_');
    // Remove trailing number ID if exists
    if (parts.length > 0 && /^\d+$/.test(parts[parts.length - 1])) {
      parts.pop();
    }
    // Filter and capitalize words
    return parts
      .filter(p => p.length > 0)
      .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
      .join(' ');
  }

  // Handle standard MD5/hash filenames
  if (/^[a-f0-9]{32}(_720w)?$/.test(nameWithoutExt) || /^[a-f0-9]{32}/.test(nameWithoutExt)) {
    // Generate description based on category
    const catName = category.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
    if (ext === '.mp4' || ext === '.webm') {
      return `Atelier Video: Handcrafting ${catName}`;
    }
    return `Eternal Petal: ${catName} Creation`;
  }

  // Fallback for general filenames
  return nameWithoutExt
    .replace(/[_-]/g, ' ')
    .replace(/\b\w/g, c => c.toUpperCase());
}

function scanDir(dir, fileList = []) {
  if (!fs.existsSync(dir)) return fileList;
  const files = fs.readdirSync(dir);

  for (const file of files) {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);

    if (stat.isDirectory()) {
      scanDir(filePath, fileList);
    } else {
      const ext = path.extname(file).toLowerCase();
      if (EXT_IMAGES.includes(ext) || EXT_VIDEOS.includes(ext)) {
        // Skip README files
        if (file.toLowerCase().startsWith('readme')) continue;

        // Relative path from public directory with GitHub Pages base path
        const relativePath = BASE_PATH + '/' + path.relative(PUBLIC_DIR, filePath).replace(/\\/g, '/');

        // Determine category based on immediate subfolder under images/
        const subPath = path.relative(IMAGES_DIR, filePath);
        const folderParts = subPath.split(path.sep);
        const category = folderParts.length > 1 ? folderParts[0] : 'general';

        const type = EXT_VIDEOS.includes(ext) ? 'video' : 'image';
        const name = KNOWN_DESCRIPTIONS[relativePath] || cleanName(file, category);

        fileList.push({
          src: relativePath,
          type,
          category,
          name
        });
      }
    }
  }

  return fileList;
}

try {
  console.log('Scanning for media in public/images...');
  const media = scanDir(IMAGES_DIR);
  console.log(`Found ${media.length} media items.`);

  const content = `// This file is auto-generated by generate-media-list.js. Do not edit manually.

export interface MediaItem {
  src: string;
  type: 'image' | 'video';
  category: string;
  name: string;
}

export const mediaItems: MediaItem[] = ${JSON.stringify(media, null, 2)} as const;
`;

  // Ensure output directory exists
  const dir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
  console.log(`Media list written to ${OUTPUT_FILE}`);
} catch (error) {
  console.error('Failed to generate media list:', error);
  process.exit(1);
}
